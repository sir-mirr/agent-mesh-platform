export async function dispatchMeshTool(
  options: MeshToolDispatcherOptions,
  name: string,
  args: Record<string, unknown>,
): Promise<MeshToolResult> {
  try {
    switch (name) {
      case "reply": {
        const to = toStringArg(args, "chat_id");
        const text = toStringArg(args, "text");
        const replyTo = typeof args.reply_to === "string" && args.reply_to.trim() !== ""
          ? args.reply_to
          : null;
        const result = (await options.hub.send({
          to,
          from: options.laneIdentity,
          content: text,
          reply_to: replyTo,
        })) as { id?: string; status?: string };
        const sentId = result.id ? ` id=${result.id}` : "";
        const status = result.status ? ` status=${result.status}` : "";
        return { content: [{ type: "text", text: `sent${sentId}${status}` }] };
      }
      case "fetch_messages": {
        const agentId = toStringArg(args, "agent_id");
        const messages = await options.hub.fetchMessages({
          agentId,
          limit: normalizeLimit(args.limit, 20, 200),
        });
        const text = messages.length === 0
          ? "(no messages)"
          : messages.map((message) => {
            const content = flattenContent(message.content);
            return `[${message.ts}] ${message.from} -> ${message.to}: ${content} (id=${message.id} status=${message.status})`;
          }).join("\n");
        return { content: [{ type: "text", text }] };
      }
      case "list_agents": {
        const agents = await options.hub.listAgents();
        const text = agents.length === 0
          ? "(no agents)"
          : agents.map((agent) => {
            const state = agent.online ? "online" : "offline";
            const type = agent.type ? ` type=${agent.type}` : "";
            const lastSeen = agent.last_seen ? ` last_seen=${agent.last_seen}` : "";
            const desc = agent.description ? ` - ${flattenContent(agent.description)}` : "";
            return `${agent.id} (${state}${type}${lastSeen})${desc}`;
          }).join("\n");
        return { content: [{ type: "text", text }] };
      }
      case "create_reminder": {
        const type = toStringArg(args, "type");
        if (type !== "once" && type !== "cron") throw new Error("type must be once or cron");
        const id = generatedReminderId(args);
        const payload = toStringArg(args, "payload");
        const schedule = reminderSchedule(type, toRecordArg(args, "schedule"));
        const context = optionalStringArg(args, "context");
        const idempotencyKey = optionalStringArg(args, "idempotency_key");
        const result = await options.hub.scheduleReminder({
          id,
          type,
          scheduleSpec: schedule.scheduleSpec,
          payload,
          nextFireAt: schedule.nextFireAt,
          ...(context === undefined ? {} : { context }),
          ...(idempotencyKey === undefined ? {} : { idempotencyKey }),
        });
        if (!result.ok) throw new Error("reminder was not created (duplicate active idempotency key)");
        const rows = await options.hub.listReminders({ status: "all", limit: 200 });
        const inserted = rows.find((row) => row.id === result.id);
        if (!inserted) throw new Error("reminder was created but could not be read back from this lane");
        return {
          content: [{
            type: "text",
            text: JSON.stringify({ ...inserted, agent_id: options.laneIdentity, created_by: options.laneIdentity }),
          }],
        };
      }
      case "list_reminders": {
        const status = optionalStringArg(args, "status") ?? "active";
        const allowedStatuses = new Set(["active", "paused", "fired", "cancelled", "exhausted", "dead", "all"]);
        if (!allowedStatuses.has(status)) throw new Error("invalid reminder status");
        const rows = await options.hub.listReminders({
          status,
          limit: normalizeLimit(args.limit, 50, 200),
        });
        return { content: [{ type: "text", text: JSON.stringify({ lane: options.laneIdentity, rows }) }] };
      }
      case "cancel_reminder": {
        const id = toStringArg(args, "id");
        const result = await options.hub.cancelReminder(id);
        if (result.changes !== 1) throw new Error("reminder not found, not active, or not owned by this lane");
        return { content: [{ type: "text", text: JSON.stringify({ id, status: "cancelled", lane: options.laneIdentity }) }] };
      }
      default:
        return { content: [{ type: "text", text: `unknown tool: ${name}` }], isError: true };
    }
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    return { content: [{ type: "text", text: `${name} failed: ${message}` }], isError: true };
  }
}
