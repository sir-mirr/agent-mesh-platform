import { randomUUID } from "node:crypto";

import { CronExpressionParser } from "cron-parser";
import type { CallToolResult } from "@modelcontextprotocol/sdk/types.js";

import type {
  MeshAgent,
  MeshMessageHistoryEntry,
  ReminderRow,
} from "./mesh-types";

export const MESH_TOOL_NAMES = [
  "reply",
  "fetch_messages",
  "list_agents",
  "create_reminder",
  "list_reminders",
  "cancel_reminder",
] as const;

export type MeshToolName = (typeof MESH_TOOL_NAMES)[number];

export interface MeshToolsHub {
  send(opts: {
    to: string;
    from: string;
    content: string;
    reply_to: string | null;
  }): Promise<unknown>;
  listAgents(): Promise<MeshAgent[]>;
  fetchMessages(opts: {
    agentId: string;
    limit?: number;
  }): Promise<MeshMessageHistoryEntry[]>;
  scheduleReminder(opts: {
    id: string;
    type: "once" | "cron";
    scheduleSpec: string;
    payload: string;
    nextFireAt: string;
    context?: string;
    idempotencyKey?: string;
  }): Promise<{ ok: boolean; id: string; type: string; next_fire_at: string }>;
  cancelReminder(id: string): Promise<{ changes: number }>;
  listReminders(opts: { status?: string; limit?: number }): Promise<ReminderRow[]>;
}

export interface MeshToolDefinition {
  name: MeshToolName;
  description: string;
  inputSchema: Record<string, unknown>;
}

export interface MeshToolResult extends CallToolResult {
  content: [{ type: "text"; text: string }];
}

export interface MeshToolDispatcherOptions {
  hub: MeshToolsHub;
  laneIdentity: string;
}

function toStringArg(args: Record<string, unknown>, name: string): string {
  const value = args[name];
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${name} is required`);
  }
  return value;
}

function normalizeLimit(value: unknown, fallback: number, max: number): number {
  const parsed =
    typeof value === "number"
      ? value
      : typeof value === "string"
        ? Number.parseInt(value, 10)
        : fallback;
  if (!Number.isInteger(parsed) || parsed <= 0) return fallback;
  return Math.min(parsed, max);
}

function flattenContent(raw: string): string {
  return raw.replace(/[\r\n]+/g, " ").trim();
}

type ReminderType = "once" | "cron";

function toRecordArg(args: Record<string, unknown>, name: string): Record<string, unknown> {
  const value = args[name];
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${name} must be an object`);
  }
  return value as Record<string, unknown>;
}

function optionalStringArg(
  args: Record<string, unknown>,
  name: string,
): string | undefined {
  const value = args[name];
  if (value === undefined) return undefined;
  if (typeof value !== "string" || value.trim() === "") {
    throw new Error(`${name} must be a non-empty string when provided`);
  }
  return value;
}

function sqliteUtc(date: Date): string {
  if (Number.isNaN(date.getTime())) throw new Error("invalid date");
  return date.toISOString().replace("T", " ").slice(0, 19);
}

function generatedReminderId(args: Record<string, unknown>): string {
  if (Object.hasOwn(args, "id")) {
    const supplied = args.id;
    if (typeof supplied !== "string" || supplied.trim() === "") {
      throw new Error("id must not be blank; reminder ids are generated by the adapter");
    }
    throw new Error("id is generated by the adapter and must not be supplied");
  }
  return `rem_${randomUUID().replace(/-/g, "")}`;
}

function createOnceSchedule(schedule: Record<string, unknown>): {
  scheduleSpec: string;
  nextFireAt: string;
} {
  const at = toStringArg(schedule, "at");
  if (!/(?:Z|[+-]\d{2}:\d{2})$/i.test(at)) {
    throw new Error("once schedule.at must include a UTC offset (for example 2026-07-13T12:00:00Z)");
  }
  const date = new Date(at);
  if (Number.isNaN(date.getTime())) throw new Error("once schedule.at is not a valid ISO-8601 time");
  if (date.getTime() <= Date.now()) throw new Error("once schedule.at must be in the future");
  return {
    scheduleSpec: JSON.stringify({ at }),
    nextFireAt: sqliteUtc(date),
  };
}

function createCronSchedule(schedule: Record<string, unknown>): {
  scheduleSpec: string;
  nextFireAt: string;
} {
  const cron = toStringArg(schedule, "cron");
  const tz = optionalStringArg(schedule, "tz") ?? "UTC";
  try {
    const next = CronExpressionParser.parse(cron, { tz }).next().toDate();
    return {
      scheduleSpec: JSON.stringify({ cron, tz }),
      nextFireAt: sqliteUtc(next),
    };
  } catch (error) {
    const detail = error instanceof Error ? error.message : String(error);
    throw new Error(`invalid cron schedule: ${detail}`);
  }
}

function reminderSchedule(
  type: ReminderType,
  schedule: Record<string, unknown>,
): { scheduleSpec: string; nextFireAt: string } {
  return type === "once" ? createOnceSchedule(schedule) : createCronSchedule(schedule);
}

